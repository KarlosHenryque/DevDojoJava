package academy.devdojo.maratonjava.introducao;

public class Aula02TiposPrimitivos {
    public static void main(String[] args) {
        System.out.println("Tipo Primitivos");

        //int, double, float, char, byte,short, long, boolean

        int age = 10;
        System.out.println("Idade: " + age);

        double height = 1.75;
        System.out.println("Tamanho: " + height);

        float wage = 1.800f;
        System.out.println("Salário: " + wage);

        boolean status = true;
        System.out.println("Esta vivo: " + status);

    }
}
